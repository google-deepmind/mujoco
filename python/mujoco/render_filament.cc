// Note: this file includes autogenerated code from:
// third_party/py/mujoco/codegen/generate_mjrf_bindings.py.
//
// The mjrf C API is composed of three types: enums, structs, and functions.
// This file generates Python wrappers/bindings for these types. Furthermore,
// it attempts to do so such that the resulting bindings are as pythonic as
// possible.
//
// Binding enums is done directly, though we remove redundant prefixes. So, e.g.
// mjrGraphicsApi becomes mjrf.GraphicsApi and mjGRAPHICS_API_DEFAULT becomes
// mjrf.GraphicsApi.GRAPHICS_API_DEFAULT.
//
// Structs are treated in two different ways. Most structs (e.g. mjrRect,
// mjrCamera, etc.) are considered to be simple POD data types. We bind these
// types directly to python and let python manage their lifetimes, creating
// copies as needed.
//
// Some structs are treated as "Objects". These map to the types that have
// explicit create/destroy functions in the C API (e.g. mjrfContext,
// mjrfTexture, mjrfLight, etc.). When created in python, their lifetimes are
// managed by a pybind11::capsule. However, when they are returned from an API
// call, they are returned such that python does not manage their lifetimes.
//
// Then, we bind the functions themselves. In almost all cases, each mjrf
// function takes a pointer to an object as its first argument. In this case,
// we actually bind the function as a method of the object itself.  So, e.g.
// `mjrf_setLightEnabled(mjrfLight*, bool)` becomes `Light.set_enabled(bool)`.
//
// Finally, to bridge the gap between Python tuple/list/numpy array types and
// the native C types (e.g. float*), we use pybind's Eigen bindings.

