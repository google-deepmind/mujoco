template <typename T, std::size_t N>
struct NumArray {
  // A reference to a vector; used for binding arguments (e.g. const &).
  using Ref = Eigen::Ref<const Eigen::Vector<T, N>>;
  // A mapping to a vector; used for returning values to existing C++ arrays.
  using Map = Eigen::Map<Eigen::Vector<T, N>>;
};

